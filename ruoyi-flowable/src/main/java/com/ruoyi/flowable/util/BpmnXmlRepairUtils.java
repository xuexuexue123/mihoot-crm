package com.ruoyi.flowable.util;

import org.w3c.dom.Document;
import org.w3c.dom.Element;
import org.w3c.dom.NodeList;
import org.xml.sax.InputSource;

import javax.xml.XMLConstants;
import javax.xml.parsers.DocumentBuilderFactory;
import javax.xml.transform.OutputKeys;
import javax.xml.transform.Transformer;
import javax.xml.transform.TransformerFactory;
import javax.xml.transform.dom.DOMSource;
import javax.xml.transform.stream.StreamResult;
import java.io.StringReader;
import java.io.StringWriter;
import java.util.HashMap;
import java.util.HashSet;
import java.util.Map;
import java.util.Objects;
import java.util.Set;

/**
 * Repairs BPMN XML generated by the React Flow designer before Flowable validates it.
 */
public class BpmnXmlRepairUtils
{
    private static final String BPMN_NS = "http://www.omg.org/spec/BPMN/20100524/MODEL";
    private static final String FLOW_PREFIX = "flow_";

    /**
     * BPMN / DI attributes whose value is an element id (IDREF / IDREFS‑like in the XSD).
     * Do not use attribute‑value rewriting for arbitrary attributes (expressions).
     */
    private static final String[] ID_REFERENCE_ATTRIBUTES =
    {
            "attachedToRef",
            "bpmnElement",
            "default",
            "errorRef",
            "escalationRef",
            "messageRef",
            "signalRef",
            "sourceRef",
            "targetRef",
    };

    private BpmnXmlRepairUtils()
    {
    }

    public static String repairReactFlowBpmnXml(String xml)
    {
        if (isBlank(xml))
        {
            return xml;
        }

        try
        {
            Document document = parseXml(xml);
            boolean changed = repairInvalidNcNames(document);

            NodeList processes = document.getElementsByTagNameNS(BPMN_NS, "process");
            if (processes.getLength() == 0)
            {
                return changed ? toXml(document) : xml;
            }

            Set<String> elementIds = collectElementIds(document);
            Set<String> sequenceFlowIds = collectSequenceFlowIds(document);

            for (int i = 0; i < processes.getLength(); i++)
            {
                Element process = (Element) processes.item(i);
                if (addMissingStartEvents(document, process, elementIds))
                {
                    changed = true;
                }
            }

            if (repairFlowReferences(document, sequenceFlowIds))
            {
                changed = true;
            }

            return changed ? toXml(document) : xml;
        }
        catch (Exception e)
        {
            // Keep the original XML so Flowable can return the real validation error.
            return xml;
        }
    }

    /**
     * Flowable XSD validation requires {@code id} and several reference attributes to be {@code xs:NCName}.
     * Some designers emit UUID‑like ids that start with a digit (invalid NCName).
     */
    private static boolean repairInvalidNcNames(Document document)
    {
        Map<String, String> remap = buildInvalidNcNameRemap(document);
        if (remap.isEmpty())
        {
            return false;
        }
        applyIdRemapToIdAttributes(document, remap);
        applyIdRemapToReferenceAttributes(document, remap);
        applyIdRemapToIncomingOutgoing(document, remap);
        return true;
    }

    private static Map<String, String> buildInvalidNcNameRemap(Document document)
    {
        Set<String> claimed = collectElementIds(document);
        Map<String, String> remap = new HashMap<String, String>();
        for (String raw : new HashSet<String>(claimed))
        {
            if (isXmlNcName(raw))
            {
                continue;
            }
            String base = "_" + raw;
            String candidate = base;
            int n = 0;
            while (claimed.contains(candidate))
            {
                n++;
                candidate = base + "_" + n;
            }
            remap.put(raw, candidate);
            claimed.remove(raw);
            claimed.add(candidate);
        }
        return remap;
    }

    private static void applyIdRemapToIdAttributes(Document document, Map<String, String> remap)
    {
        NodeList elements = document.getElementsByTagName("*");
        for (int i = 0; i < elements.getLength(); i++)
        {
            Element element = (Element) elements.item(i);
            if (!element.hasAttribute("id"))
            {
                continue;
            }
            String id = element.getAttribute("id");
            String neo = remap.get(id);
            if (neo != null)
            {
                element.setAttribute("id", neo);
            }
        }
    }

    private static void applyIdRemapToReferenceAttributes(Document document, Map<String, String> remap)
    {
        NodeList elements = document.getElementsByTagName("*");
        for (int i = 0; i < elements.getLength(); i++)
        {
            Element element = (Element) elements.item(i);
            for (String attributeName : ID_REFERENCE_ATTRIBUTES)
            {
                if (!element.hasAttribute(attributeName))
                {
                    continue;
                }
                rewriteAttributeIfRemapped(element, attributeName, remap);
            }

            rewriteIdRefsAttribute(element, remap);
        }
    }

    /**
     * Parses {@code xsi:type="IDs"} / {@code idRefs} style attributes (space‑separated ids).
     */
    private static void rewriteIdRefsAttribute(Element element, Map<String, String> remap)
    {
        if (!element.hasAttribute("idRefs"))
        {
            return;
        }
        String val = element.getAttribute("idRefs");
        if (isBlank(val))
        {
            return;
        }
        String[] parts = val.trim().split("\\s+");
        boolean changed = false;
        for (int i = 0; i < parts.length; i++)
        {
            String neo = remap.get(parts[i]);
            if (neo != null)
            {
                parts[i] = neo;
                changed = true;
            }
        }
        if (changed)
        {
            element.setAttribute("idRefs", String.join(" ", parts));
        }
    }

    private static void rewriteAttributeIfRemapped(Element element, String attributeName, Map<String, String> remap)
    {
        String val = element.getAttribute(attributeName);
        String neo = remap.get(val);
        if (neo != null)
        {
            element.setAttribute(attributeName, neo);
        }
    }

    private static void applyIdRemapToIncomingOutgoing(Document document, Map<String, String> remap)
    {
        NodeList elements = document.getElementsByTagName("*");
        for (int i = 0; i < elements.getLength(); i++)
        {
            Element element = (Element) elements.item(i);
            String localName = element.getLocalName();
            if (!"incoming".equals(localName) && !"outgoing".equals(localName))
            {
                continue;
            }
            String flowId = trim(element.getTextContent());
            String neo = remap.get(flowId);
            if (neo != null && !Objects.equals(flowId, neo))
            {
                element.setTextContent(neo);
            }
        }
    }

    /** Conservative NCName check (sufficient for typical BPMN imports; ASCII‑centric designers). */
    private static boolean isXmlNcName(String name)
    {
        int len = name.length();
        if (len == 0)
        {
            return false;
        }
        if (!Character.isLetter(name.charAt(0)) && name.charAt(0) != '_')
        {
            return false;
        }
        for (int i = 1; i < len; i++)
        {
            char c = name.charAt(i);
            if (Character.isLetterOrDigit(c) || c == '_' || c == '-' || c == '.')
            {
                continue;
            }
            return false;
        }
        return true;
    }

    private static Document parseXml(String xml) throws Exception
    {
        DocumentBuilderFactory factory = DocumentBuilderFactory.newInstance();
        factory.setNamespaceAware(true);
        factory.setFeature(XMLConstants.FEATURE_SECURE_PROCESSING, true);
        factory.setFeature("http://apache.org/xml/features/disallow-doctype-decl", true);
        return factory.newDocumentBuilder().parse(new InputSource(new StringReader(xml)));
    }

    private static Set<String> collectElementIds(Document document)
    {
        Set<String> elementIds = new HashSet<String>();
        NodeList elements = document.getElementsByTagName("*");
        for (int i = 0; i < elements.getLength(); i++)
        {
            Element element = (Element) elements.item(i);
            if (element.hasAttribute("id"))
            {
                elementIds.add(element.getAttribute("id"));
            }
        }
        return elementIds;
    }

    private static Set<String> collectSequenceFlowIds(Document document)
    {
        Set<String> sequenceFlowIds = new HashSet<String>();
        NodeList sequenceFlows = document.getElementsByTagNameNS(BPMN_NS, "sequenceFlow");
        for (int i = 0; i < sequenceFlows.getLength(); i++)
        {
            Element sequenceFlow = (Element) sequenceFlows.item(i);
            if (sequenceFlow.hasAttribute("id"))
            {
                sequenceFlowIds.add(sequenceFlow.getAttribute("id"));
            }
        }
        return sequenceFlowIds;
    }

    private static boolean addMissingStartEvents(Document document, Element process, Set<String> elementIds)
    {
        boolean changed = false;
        NodeList sequenceFlows = process.getElementsByTagNameNS(BPMN_NS, "sequenceFlow");
        for (int i = 0; i < sequenceFlows.getLength(); i++)
        {
            Element sequenceFlow = (Element) sequenceFlows.item(i);
            if (sequenceFlow.getParentNode() != process)
            {
                continue;
            }

            String sourceRef = sequenceFlow.getAttribute("sourceRef");
            if (!isReactFlowGeneratedRef(sourceRef) || elementIds.contains(sourceRef))
            {
                continue;
            }

            Element startEvent = document.createElementNS(BPMN_NS, qName(process, "startEvent"));
            startEvent.setAttribute("id", sourceRef);
            startEvent.setAttribute("name", "Start");

            Element outgoing = document.createElementNS(BPMN_NS, qName(process, "outgoing"));
            outgoing.setTextContent(sequenceFlow.getAttribute("id"));
            startEvent.appendChild(outgoing);

            process.insertBefore(startEvent, sequenceFlow);
            elementIds.add(sourceRef);
            changed = true;
        }
        return changed;
    }

    private static boolean repairFlowReferences(Document document, Set<String> sequenceFlowIds)
    {
        boolean changed = false;
        NodeList elements = document.getElementsByTagName("*");
        for (int i = 0; i < elements.getLength(); i++)
        {
            Element element = (Element) elements.item(i);
            String localName = element.getLocalName();
            if (!"incoming".equals(localName) && !"outgoing".equals(localName))
            {
                continue;
            }

            String flowId = trim(element.getTextContent());
            String prefixedFlowId = FLOW_PREFIX + flowId;
            if (!sequenceFlowIds.contains(flowId) && sequenceFlowIds.contains(prefixedFlowId))
            {
                element.setTextContent(prefixedFlowId);
                changed = true;
            }
        }
        return changed;
    }

    private static boolean isReactFlowGeneratedRef(String ref)
    {
        return !isBlank(ref) && ref.startsWith("id_");
    }

    private static String qName(Element context, String localName)
    {
        String prefix = context.getPrefix();
        return isBlank(prefix) ? localName : prefix + ":" + localName;
    }

    private static String toXml(Document document) throws Exception
    {
        TransformerFactory transformerFactory = TransformerFactory.newInstance();
        transformerFactory.setFeature(XMLConstants.FEATURE_SECURE_PROCESSING, true);
        Transformer transformer = transformerFactory.newTransformer();
        transformer.setOutputProperty(OutputKeys.ENCODING, "UTF-8");
        transformer.setOutputProperty(OutputKeys.OMIT_XML_DECLARATION, "no");

        StringWriter writer = new StringWriter();
        transformer.transform(new DOMSource(document), new StreamResult(writer));
        return writer.toString();
    }

    private static boolean isBlank(String value)
    {
        return value == null || value.trim().length() == 0;
    }

    private static String trim(String value)
    {
        return value == null ? "" : value.trim();
    }
}
